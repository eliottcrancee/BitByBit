#[cfg(test)]
mod sap1_program_tests {
    use super::*;

    fn run_program(program: &[u8], max_steps: usize) -> Sap1 {
        let mut cpu = Sap1::default();
        cpu.load_program(program).expect("load failed");
        cpu.run(max_steps).expect("run failed");
        cpu
    }

    #[test]
    fn test_transistor_count() {
        let cpu = Sap1::default();
        assert!(cpu.transistor_count() > 0);
    }

    #[test]
    fn test_nop_instruction() {
        let cpu = run_program(&[0x00, 0xF0], 100); // NOP, HLT
        assert!(cpu.halted());
        assert_eq!(bits_to_int(&cpu.out(), false), 0);
    }

    #[test]
    fn test_ldi_instruction() {
        let cpu = run_program(&[0x5A, 0xF0], 100); // LDI 10, HLT
        assert!(cpu.halted());
        assert_eq!(bits_to_int(&cpu.out(), false), 10);
    }

    #[test]
    fn test_lda_and_sta_instructions() {
        // LDI 7, STA 0xA, LDI 0, LDA 0xA, HLT
        let cpu = run_program(&[0x57, 0x4A, 0x50, 0x1A, 0xF0], 100);
        assert!(cpu.halted());
        assert_eq!(bits_to_int(&cpu.out(), false), 7);
    }

    #[test]
    fn test_add_instruction() {
        // LDI 5, ADD 0xE, HLT (mem[0xE] = 3)
        let mut program: Vec<u8> = vec![0x55, 0x2E, 0xF0];
        program.extend(std::iter::repeat_n(0, 11));
        program.extend([3, 0]);

        let cpu = run_program(&program, 100);

        assert!(cpu.halted());
        assert_eq!(bits_to_int(&cpu.out(), false), 8);
    }

    #[test]
    fn test_sub_instruction() {
        // LDI 9, SUB 0xE, HLT (mem[0xE] = 4)
        let mut program: Vec<u8> = vec![0x59, 0x3E, 0xF0];
        program.extend(std::iter::repeat_n(0, 11));
        program.extend([4, 0]);

        let cpu = run_program(&program, 100);

        assert!(cpu.halted());
        assert_eq!(bits_to_int(&cpu.out(), false), 5);
    }

    #[test]
    fn test_jmp_instruction() {
        // 0: JMP 3, 1: LDI 9 (skipped), 2: HLT, 3: LDI 4, 4: HLT
        let cpu = run_program(&[0x63, 0x59, 0xF0, 0x54, 0xF0], 100);
        assert!(cpu.halted());
        assert_eq!(bits_to_int(&cpu.out(), false), 4);
    }

    fn with_operand_at_e(program: &[u8], operand: u8) -> Vec<u8> {
        let mut full: Vec<u8> = program.to_vec();
        full.resize(14, 0);
        full.extend([operand, 0]); // mem[0xE] = operand
        full
    }

    #[test]
    fn test_jz_taken() {
        // 0: LDI 3, 1: SUB 0xE (3 - 3 = 0), 2: JZ 5, 3: LDI 9,
        // 4: HLT, 5: LDI 6, 6: HLT
        let program = with_operand_at_e(&[0x53, 0x3E, 0x75, 0x59, 0xF0, 0x56, 0xF0], 3);
        let cpu = run_program(&program, 100);
        assert!(cpu.halted());
        assert_eq!(bits_to_int(&cpu.out(), false), 6);
    }

    #[test]
    fn test_jz_not_taken() {
        // 0: LDI 4, 1: SUB 0xE (4 - 3 = 1), 2: JZ 5 (not taken),
        // 3: LDI 9, 4: HLT
        let program = with_operand_at_e(&[0x54, 0x3E, 0x75, 0x59, 0xF0, 0x56, 0xF0], 3);
        let cpu = run_program(&program, 100);
        assert!(cpu.halted());
        assert_eq!(bits_to_int(&cpu.out(), false), 9);
    }

    #[test]
    fn test_jc_taken() {
        // 0: LDI 10, 1: ADD 0xE (10 + 250 = 260 -> carry), 2: JC 5,
        // 3: LDI 9, 4: HLT, 5: LDI 6, 6: HLT
        let program = with_operand_at_e(&[0x5A, 0x2E, 0x85, 0x59, 0xF0, 0x56, 0xF0], 250);
        let cpu = run_program(&program, 100);
        assert!(cpu.halted());
        assert_eq!(bits_to_int(&cpu.out(), false), 6);
    }

    #[test]
    fn test_jc_not_taken() {
        // 0: LDI 2, 1: ADD 0xE (2 + 3 = 5, no carry), 2: JC 5 (not taken)
        let program = with_operand_at_e(&[0x52, 0x2E, 0x85, 0x59, 0xF0, 0x56, 0xF0], 3);
        let cpu = run_program(&program, 100);
        assert!(cpu.halted());
        assert_eq!(bits_to_int(&cpu.out(), false), 9);
    }

    #[test]
    fn test_loop_multiplication_program() {
        // Multiply 3 by 5 using a loop.
        let program = [
            0x1F, // 0: LDA 0xF (load accumulator / running sum)
            0x2E, // 1: ADD 0xE (add 3)
            0x4F, // 2: STA 0xF (store back to running sum)
            0x1D, // 3: LDA 0xD (load count)
            0x3C, // 4: SUB 0xC (subtract 1)
            0x79, // 5: JZ 9 (if count reached 0, jump to 9)
            0x4D, // 6: STA 0xD (save decremented count)
            0x60, // 7: JMP 0 (loop back to LDA 0xF)
            0x00, // 8: NOP
            0x1F, // 9: LDA 0xF (load final sum)
            0xF0, // A: HLT
            0x00, // B: unused
            0x01, // C: constant 1
            0x05, // D: initial count = 5
            0x03, // E: constant 3
            0x00, // F: sum initialized to 0
        ];

        let cpu = run_program(&program, 500);

        assert!(cpu.halted());
        assert_eq!(bits_to_int(&cpu.out(), false), 15);
    }

    #[test]
    fn test_clock_tick_and_micro_step() {
        let mut cpu = Sap1::default();
        cpu.load_program(&[0x57, 0xF0]).expect("load failed"); // LDI 7, HLT

        // Advance step by step using clock_tick.
        assert_eq!(cpu.clock(), Bit::Low);
        assert_eq!(cpu.clock_tick().expect("clock tick failed"), Bit::High);
        assert_eq!(cpu.clock_tick().expect("clock tick failed"), Bit::Low);

        // Run with micro_step.
        cpu.micro_step().expect("micro step failed");
        assert!(!cpu.halted());

        cpu.run(100).expect("run failed");
        assert!(cpu.halted());
        assert_eq!(bits_to_int(&cpu.out(), false), 7);
    }

    #[test]
    fn test_halted_clock_stops() {
        let mut cpu = Sap1::default();
        cpu.load_program(&[0xF0]).expect("load failed"); // HLT only
        cpu.run(10).expect("run failed");
        assert!(cpu.halted());

        // Once halted, the clock no longer toggles.
        let clock_before = cpu.clock();
        cpu.clock_tick().expect("clock tick failed");
        assert_eq!(cpu.clock(), clock_before);
    }
}
